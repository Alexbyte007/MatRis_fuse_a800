import argparse
import csv
import gzip
import json
from pathlib import Path


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Join WBM raw prediction records with WBM summary ground truth by material_id."
    )
    parser.add_argument(
        "--predictions-jsonl",
        required=True,
        help="Path to per_structure_predictions.jsonl generated by run_wbm_eval.py",
    )
    parser.add_argument(
        "--wbm-summary",
        default="/home/lht/lab/wbm/2023-12-13-wbm-summary.csv.gz",
        help="Path to WBM summary csv.gz",
    )
    parser.add_argument(
        "--output-csv",
        required=True,
        help="Path to save the joined csv table",
    )
    return parser.parse_args()


def load_prediction_rows(path: str) -> list[dict]:
    rows: list[dict] = []
    with open(path, "r", encoding="utf-8") as fp:
        for line in fp:
            rows.append(json.loads(line))
    return rows


def load_summary_lookup(path: str) -> dict[str, dict]:
    lookup: dict[str, dict] = {}
    with gzip.open(path, "rt", encoding="utf-8", newline="") as fp:
        reader = csv.DictReader(fp)
        for row in reader:
            lookup[row["material_id"]] = row
    return lookup


def main() -> None:
    args = parse_args()
    prediction_rows = load_prediction_rows(args.predictions_jsonl)
    summary_lookup = load_summary_lookup(args.wbm_summary)

    joined_rows: list[dict] = []
    missing_ids: list[str] = []

    for pred in prediction_rows:
        material_id = pred["material_id"]
        summary_row = summary_lookup.get(material_id)
        if summary_row is None:
            missing_ids.append(material_id)
            continue

        joined_rows.append(
            {
                "material_id": material_id,
                "formula_from_cse": pred.get("formula_from_cse", ""),
                "n_atoms": pred.get("n_atoms", ""),
                "pred_relaxed_energy_eV": pred.get("pred_relaxed_energy_eV", ""),
                "num_relax_frames": pred.get("num_relax_frames", ""),
                "latency_ms": pred.get("latency_ms", ""),
                "formula": summary_row.get("formula", ""),
                "n_sites": summary_row.get("n_sites", ""),
                "uncorrected_energy": summary_row.get("uncorrected_energy", ""),
                "e_form_per_atom_uncorrected": summary_row.get(
                    "e_form_per_atom_uncorrected", ""
                ),
                "e_form_per_atom_mp2020_corrected": summary_row.get(
                    "e_form_per_atom_mp2020_corrected", ""
                ),
                "e_above_hull_mp2020_corrected_ppd_mp": summary_row.get(
                    "e_above_hull_mp2020_corrected_ppd_mp", ""
                ),
                "e_correction_per_atom_mp2020": summary_row.get(
                    "e_correction_per_atom_mp2020", ""
                ),
                "unique_prototype": summary_row.get("unique_prototype", ""),
            }
        )

    enriched_rows: list[dict] = []
    for row in joined_rows:
        pred_relaxed_energy_eV = float(row["pred_relaxed_energy_eV"])
        uncorrected_energy = float(row["uncorrected_energy"])
        n_atoms = float(row["n_atoms"])
        e_form_per_atom_mp2020_corrected = float(
            row["e_form_per_atom_mp2020_corrected"]
        )

        energy_delta_eV = pred_relaxed_energy_eV - uncorrected_energy
        energy_delta_per_atom_eV = energy_delta_eV / n_atoms
        e_form_per_atom_matris_from_relaxed_energy = (
            e_form_per_atom_mp2020_corrected + energy_delta_per_atom_eV
        )

        enriched_rows.append(
            row
            | {
                "energy_delta_eV": energy_delta_eV,
                "energy_delta_per_atom_eV": energy_delta_per_atom_eV,
                "e_form_per_atom_matris_from_relaxed_energy": e_form_per_atom_matris_from_relaxed_energy,
            }
        )

    output_path = Path(args.output_csv)
    output_path.parent.mkdir(parents=True, exist_ok=True)

    fieldnames = [
        "material_id",
        "formula_from_cse",
        "n_atoms",
        "pred_relaxed_energy_eV",
        "num_relax_frames",
        "latency_ms",
        "formula",
        "n_sites",
        "uncorrected_energy",
        "energy_delta_eV",
        "energy_delta_per_atom_eV",
        "e_form_per_atom_uncorrected",
        "e_form_per_atom_mp2020_corrected",
        "e_form_per_atom_matris_from_relaxed_energy",
        "e_above_hull_mp2020_corrected_ppd_mp",
        "e_correction_per_atom_mp2020",
        "unique_prototype",
    ]
    with open(output_path, "w", encoding="utf-8", newline="") as fp:
        writer = csv.DictWriter(fp, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(enriched_rows)

    print(f"Joined rows written: {len(enriched_rows)}")
    print(f"Output CSV: {output_path}")
    if missing_ids:
        print(f"Missing material_id count: {len(missing_ids)}")
        print("Missing ids:", ", ".join(missing_ids))
    else:
        print("All prediction rows matched WBM summary.")


if __name__ == "__main__":
    main()
